using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace ZigBeeNet.EmberV8Plus.CodeGenerator.Utility
{
    public static class TextHelper
    {
        public static void AppendAutoGeneratedHeader(StringBuilder sb)
        {
            sb.AppendLine("//------------------------------------------------------------------------------");
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     This code was generated by a tool.");
            sb.AppendLine("//");
            sb.AppendLine("//     Changes to this file may cause incorrect behavior and will be lost if");
            sb.AppendLine("//     the code is regenerated.");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("//------------------------------------------------------------------------------");
            sb.AppendLine();
        }

        public static void AppendBasicSummary(StringBuilder sb, string description, int indentation = 0)
        {
            if (!string.IsNullOrWhiteSpace(description))
            {
                string indent = new string('\t', indentation);

                sb.AppendLine($"{indent}/// <summary>");
                sb.AppendLine($"{indent}/// {description.XmlEscape()}");
                sb.AppendLine($"{indent}/// </summary>");
            }
        }

        public static int GetArrayDefinitionSize(this string cTypeString)
        {
            int startIndex = cTypeString.IndexOf('[');
            int endIndex = cTypeString.IndexOf(']');
            if (startIndex >= 0 && endIndex > startIndex)
            {
                bool isNumeric = int.TryParse(cTypeString.Substring(startIndex + 1, endIndex - startIndex - 1), out int arraySize);
                if (isNumeric)
                {
                    return arraySize;
                }
                else
                {
                    return -1; // Variable length array
                }
            }
            return 0; // Not an array
        }

        public static string GetArrayDefinitionSymbolicSize(this string cTypeString)
        {
            int startIndex = cTypeString.IndexOf('[');
            int endIndex = cTypeString.IndexOf(']');
            if (startIndex >= 0 && endIndex > startIndex)
            {
                return cTypeString.Substring(startIndex + 1, endIndex - startIndex - 1);
            }
            else
            {
                return string.Empty;
            }
        }


        public static string GetArrayDefinitionBaseType(this string cTypeString)
        {
            int startIndex = cTypeString.IndexOf('[');
            if (startIndex >= 0)
            {
                return cTypeString.Substring(0, startIndex).Trim();
            }
            return cTypeString.Trim();
        }

        public static bool IsArrayTypeDefinition(this string cTypeString)
        {
            return cTypeString.Contains('[') && cTypeString.Contains(']');
        }

        public static IEnumerable<string> ReadAllLines(this string text)
        {
            if (text == null) throw new ArgumentNullException(nameof(text));

            using var reader = new StringReader(text);
            string? line;
            while ((line = reader.ReadLine()) != null)
            {
                yield return line;
            }
        }

    }
}
