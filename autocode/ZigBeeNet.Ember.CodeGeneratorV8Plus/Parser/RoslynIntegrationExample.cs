        /// <summary>
        /// Demonstrates the key differences in approach.
        /// </summary>
        public void ComparisonExample()
        {
            // ORIGINAL APPROACH - Manual string building
            var sb = new StringBuilder();
            sb.AppendLine("public class Example");
            sb.AppendLine("{");
            sb.AppendLine("\tpublic void Method()");
            sb.AppendLine("\t{");
            sb.AppendLine("\t}");
            sb.AppendLine("}");
            string stringBuilderResult = sb.ToString();

            // ROSLYN APPROACH - Syntax tree construction
            var classDecl = SyntaxFactory.ClassDeclaration("Example")
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .AddMembers(
                    SyntaxFactory.MethodDeclaration(
                        SyntaxFactory.PredefinedType(SyntaxFactory.Token(SyntaxKind.VoidKeyword)),
                        "Method")
                    .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                    .WithBody(SyntaxFactory.Block()));

            var compilationUnit = SyntaxFactory.CompilationUnit()
                .AddMembers(classDecl)
                .NormalizeWhitespace();

            string roslynResult = compilationUnit.ToFullString();

            // Both produce identical output, but Roslyn is type-safe and maintainable
        }

        /// <summary>
        /// Shows how to handle XML documentation with Roslyn.
        /// </summary>
        public string GenerateMethodWithDocumentation(
            string methodName,
            string description,
            List<string> parameterNames,
            List<string> parameterDescriptions)
        {
            var trivia = new List<SyntaxTrivia>();

            // Add summary
            trivia.Add(SyntaxFactory.Comment("/// <summary>"));
            trivia.Add(SyntaxFactory.Comment($"/// {description}"));
            trivia.Add(SyntaxFactory.Comment("/// </summary>"));

            // Add parameters
            for (int i = 0; i < parameterNames.Count; i++)
            {
                string paramDesc = i < parameterDescriptions.Count 
                    ? parameterDescriptions[i] 
                    : "Parameter";
                trivia.Add(SyntaxFactory.Comment(
                    $"/// <param name=\"{parameterNames[i]}\">{paramDesc}</param>"));
            }

            // Add returns
            trivia.Add(SyntaxFactory.Comment("/// <returns>The result</returns>"));

            var method = SyntaxFactory.MethodDeclaration(
                SyntaxFactory.PredefinedType(SyntaxFactory.Token(SyntaxKind.VoidKeyword)),
                methodName)
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .WithBody(SyntaxFactory.Block())
                .WithLeadingTrivia(SyntaxFactory.TriviaList(trivia));

            return method.ToFullString();
        }

        /// <summary>
        /// Demonstrates tuple return type generation for multiple response arguments.
        /// </summary>
        public string GenerateTupleReturnMethod()
        {
            // Create tuple elements
            var tupleElements = new[]
            {
                SyntaxFactory.TupleElement(
                    SyntaxFactory.ParseTypeName("EmberStatus"),
                    SyntaxFactory.Identifier("status")),
                SyntaxFactory.TupleElement(
                    SyntaxFactory.ParseTypeName("int"),
                    SyntaxFactory.Identifier("value")),
                SyntaxFactory.TupleElement(
                    SyntaxFactory.ParseTypeName("string"),
                    SyntaxFactory.Identifier("message"))
            };

            var returnType = SyntaxFactory.TupleType(
                SyntaxFactory.SeparatedList(tupleElements));

            var method = SyntaxFactory.MethodDeclaration(returnType, "GetMultipleValues")
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .WithBody(SyntaxFactory.Block(
                    SyntaxFactory.ReturnStatement(
                        SyntaxFactory.TupleExpression(
                            SyntaxFactory.SeparatedList(new[]
                            {
                                SyntaxFactory.Argument(SyntaxFactory.IdentifierName("status")),
                                SyntaxFactory.Argument(SyntaxFactory.IdentifierName("value")),
                                SyntaxFactory.Argument(SyntaxFactory.IdentifierName("message"))
                            })))));

            return method.ToFullString();
        }

        /// <summary>
        /// Shows how to generate method parameters from FrameArgument list.
        /// </summary>
        public string GenerateMethodWithParameters(List<FrameArgument> arguments)
        {
            var parameters = arguments
                .Select(arg => SyntaxFactory.Parameter(
                    SyntaxFactory.Identifier(arg.Name))
                    .WithType(SyntaxFactory.ParseTypeName(arg.Type)))
                .ToArray();

            var method = SyntaxFactory.MethodDeclaration(
                SyntaxFactory.PredefinedType(SyntaxFactory.Token(SyntaxKind.VoidKeyword)),
                "ProcessArguments")
                .AddModifiers(SyntaxFactory.Token(SyntaxKind.PublicKeyword))
                .AddParameterListParameters(parameters)
                .WithBody(SyntaxFactory.Block());

            return method.ToFullString();
        }
